// Generates the V-OS release signing key pair (ECDSA P-256).
// Usage:  dotnet run build/tools/release-keygen.cs -- <private-key.pem> <ReleaseKey.cs>
// The private key must never be committed. Keep a backup: without it, installed copies
// cannot verify future updates (V-OS rejects unsigned or wrongly signed releases).
using System.Security.Cryptography;

if (args.Length < 2) { Console.Error.WriteLine("usage: release-keygen <private-key.pem> <ReleaseKey.cs>"); return 2; }
var privatePath = Path.GetFullPath(args[0]);
var publicCs = Path.GetFullPath(args[1]);
if (File.Exists(privatePath)) { Console.Error.WriteLine($"Refusing to overwrite existing key: {privatePath}"); return 3; }

using var key = ECDsa.Create(ECCurve.NamedCurves.nistP256);
Directory.CreateDirectory(Path.GetDirectoryName(privatePath)!);
File.WriteAllText(privatePath, key.ExportPkcs8PrivateKeyPem());
var publicPem = key.ExportSubjectPublicKeyInfoPem();
File.WriteAllText(publicCs,
    "namespace VOS.Core.Updates;\n\n" +
    "/// <summary>Public half of the V-OS release signing key (ECDSA P-256). Generated by build/tools/release-keygen.cs.</summary>\n" +
    "public static class ReleaseKey\n{\n    public const string PublicKeyPem = \"\"\"\n" + publicPem.Trim() + "\n\"\"\";\n}\n");
Console.WriteLine($"Private key: {privatePath}");
Console.WriteLine($"Public key:  {publicCs}");
return 0;
